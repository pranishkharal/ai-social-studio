"""
themes.py — Named looks for ai-social-studio clips.

A theme bundles a karaoke caption style, caption colours, the hook-box
colours, the progress bar and watermark hints, all in ``themes.json`` next
to this module. The ``clean`` theme is the current default look (white
hook box, black text, no progress bar), so picking no theme changes
nothing.

Selection order: an explicit ``theme=`` argument, then the ``CLIP_THEME``
env var, then ``clean``. An unknown name falls back to ``clean`` (with a
log line) instead of failing a render.

Wired into ``clip_editor``: the hook-box fill/text colours go into
``generate_screen_caption_card`` and the progress bar (when the theme
enables it) is drawn by ``render_modes.build_progress_bar_filter``. The
caption style maps to the karaoke styles in ``karaoke_subtitles.STYLES``;
the watermark fields are hints for a future watermark restyle — the Kick
bar itself is generated by ``kick_program`` and is untouched by themes.

Adapted from gta6-clipper (https://gitlab.com/nocodehack.io/gta6-clipper,
MIT licence), themes.json — the theme *idea* and the same five-look
structure, with colours and keys fitted to this repo's renderer.
"""

import json
import os
from pathlib import Path

THEMES_FILE = Path(__file__).resolve().parent / "themes.json"
DEFAULT_THEME = "clean"
ENV_VAR = "CLIP_THEME"

_cache = None


def _load_raw():
    """Parse themes.json once per process (tests can reset _cache)."""
    global _cache
    if _cache is None:
        try:
            with open(THEMES_FILE, encoding="utf-8") as f:
                _cache = json.load(f)
        except (OSError, ValueError):
            _cache = {"themes": []}
    return _cache


def list_themes():
    """[(name, label)] for every theme in themes.json."""
    return [(t.get("name", ""), t.get("label", t.get("name", "")))
            for t in _load_raw().get("themes", []) if t.get("name")]


def get_theme(name=None):
    """
    Resolve a theme name to its dict. None (or "") means the CLIP_THEME
    env var, then "clean". Unknown names fall back to "clean".
    """
    wanted = (name or os.environ.get(ENV_VAR, "") or DEFAULT_THEME)
    wanted = str(wanted).strip().lower()
    themes = _load_raw().get("themes", [])
    for theme in themes:
        if str(theme.get("name", "")).lower() == wanted:
            return dict(theme)
    if wanted != DEFAULT_THEME:
        try:
            from database import log_event
            log_event("WARNING", "Themes",
                      f"Unknown theme {wanted!r}; falling back to 'clean'")
        except Exception:
            pass
    for theme in themes:
        if str(theme.get("name", "")).lower() == DEFAULT_THEME:
            return dict(theme)
    return {"name": DEFAULT_THEME}


def hex_to_rgb(hex_color, default=(255, 255, 255)):
    """'#FFE500' / 'FFE500' -> (255, 229, 0); garbage -> ``default``."""
    try:
        h = str(hex_color).strip().lstrip("#")
        if len(h) == 3:  # short form: "F00" -> "FF0000"
            h = "".join(c * 2 for c in h)
        if len(h) != 6:
            return default
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    except (TypeError, ValueError):
        return default


def hook_colors(theme):
    """
    (box_rgba, text_rgba) for the hook banner card of a theme dict (or a
    theme name). Defaults are the current look: white box, near-black
    text.
    """
    if isinstance(theme, str) or theme is None:
        theme = get_theme(theme)
    box = hex_to_rgb(theme.get("hook_box", "FFFFFF"), (255, 255, 255))
    text = hex_to_rgb(theme.get("hook_text", "0A0A0A"), (10, 10, 10))
    return box + (255,), text + (255,)


def progress_bar(theme):
    """
    (enabled, color_hex) for the theme's progress bar. The colour is
    returned as a 6-digit hex string without '#'.
    """
    if isinstance(theme, str) or theme is None:
        theme = get_theme(theme)
    color = str(theme.get("progress_color", "FFE500")).strip().lstrip("#")
    if len(color) != 6:
        color = "FFE500"
    return bool(theme.get("progress")), color


def caption_style(theme):
    """
    Karaoke style name for a theme dict (or name): "hormozi" or
    "minimal". Unknown values fall back to "hormozi".
    """
    if isinstance(theme, str) or theme is None:
        theme = get_theme(theme)
    style = str(theme.get("caption_style", "hormozi")).strip().lower()
    return style if style in ("hormozi", "minimal") else "hormozi"
